// ───────────────────────── Normalisation ─────────────────────────

const INDIC = { "٠": "0", "١": "1", "٢": "2", "٣": "3", "٤": "4", "٥": "5", "٦": "6", "٧": "7", "٨": "8", "٩": "9" };

function normName(s) {
  return String(s || "")
    .normalize("NFKC")
    .replace(/[\u064B-\u065F\u0670\u0640]/g, "") // tashkeel + tatweel
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}

// clé indépendante de l'ordre des mots (ex: "جبران حسناء" == "حسناء جبران")
function nameKey(s) {
  return normName(s).split(" ").filter(Boolean).sort().join(" ");
}

function normCin(s) {
  const v = String(s || "").toUpperCase().replace(/[^A-Z0-9]/g, "");
  return v ? v.slice(0, 20) : null;
}

function digitsOf(s) {
  return String(s || "").replace(/[٠-٩]/g, (d) => INDIC[d]).replace(/\D/g, "");
}

function normPhone(s) {
  let d = digitsOf(s);
  if (!d) return null;
  if (d.length === 9 && /^[5-7]/.test(d)) d = "0" + d;
  return d.slice(0, 20);
}

function rawPhone(s) {
  const v = String(s || "").replace(/\s+/g, " ").trim();
  return digitsOf(v) ? v.slice(0, 20) : null; // pas de chiffres (ex: texte) -> NULL
}

function rawCin(s) {
  const v = String(s || "").replace(/\s+/g, " ").trim();
  return v ? v.slice(0, 20) : null;
}

// ───────────────────────── Insertion ─────────────────────────

async function bulkInsert(tx, table, cols, rows, size = 200) {
  for (let i = 0; i < rows.length; i += size) {
    await tx.query(`INSERT INTO ${table} (${cols.join(", ")}) VALUES ?`, [rows.slice(i, i + size)]);
  }
}

function buildRows() {
  const warnings = [];
  const sponsorRows = [];
  const familyRows = [];
  const memberRows = [];
  const seenCin = new Set();
  let sponsorId = 0;
  let familyId = 0;

  for (const s of DATA) {
    sponsorId = s.id;
    const parentId = s.parent || null;
    if (parentId !== null && parentId >= sponsorId) throw new Error(`Parent mal ordonné pour ${s.name}`);
    sponsorRows.push([sponsorId, s.name, normName(s.name), nameKey(s.name), null, null, null, null, s.type, parentId]);

    for (const f of s.families || []) {
      familyId += 1;
      const rep = f.members[f.rep];
      const famPhone = rawPhone(rep[2]) || (f.members.map((m) => rawPhone(m[2])).find(Boolean) || null);
      familyRows.push([familyId, sponsorId, famPhone, normPhone(famPhone), null, null]);

      f.members.forEach((m, i) => {
        const [name, cin, phone] = m;
        let cinNorm = normCin(cin);
        if (cinNorm) {
          if (seenCin.has(cinNorm)) {
            warnings.push(`CIN en double (${cin}) pour « ${name} » (parrain ${s.name}) : conservé dans cin, cin_norm = NULL`);
            cinNorm = null;
          } else {
            seenCin.add(cinNorm);
          }
        }
        const p = rawPhone(phone);
        if (p && !/^0[5-7]\d{8}$/.test(normPhone(p))) {
          warnings.push(`Téléphone suspect « ${p} » pour « ${name} » (parrain ${s.name})`);
        }
        memberRows.push([familyId, name, normName(name), nameKey(name), rawCin(cin), cinNorm, p, normPhone(p), i === f.rep ? 1 : 0]);
      });
    }
  }
  return { sponsorRows, familyRows, memberRows, warnings };
}

export default async function handler(req, res) {
  res.setHeader("Cache-Control", "no-store");
  if (req.method !== "GET" && req.method !== "POST") {
    res.setHeader("Allow", "GET, POST");
    return res.status(405).json({ ok: false, error: "Method not allowed" });
  }

  try {
    const [c] = await query(
      "SELECT (SELECT COUNT(*) FROM sponsors) AS sponsors, (SELECT COUNT(*) FROM families) AS families, (SELECT COUNT(*) FROM family_members) AS members"
    );
    if (Number(c.sponsors) + Number(c.families) + Number(c.members) > 0) {
      return res.status(409).json({ ok: false, error: "Les tables sponsors / families / family_members ne sont pas vides", existing: c });
    }

    const { sponsorRows, familyRows, memberRows, warnings } = buildRows();

    await withTransaction(async (tx) => {
      await bulkInsert(
        tx,
        "sponsors",
        ["id", "full_name", "name_norm", "name_key", "cin", "cin_norm", "phone", "phone_norm", "type", "parent_id"],
        sponsorRows
      );
      await bulkInsert(tx, "families", ["id", "sponsor_id", "phone", "phone_norm", "address", "created_by"], familyRows);
      await bulkInsert(
        tx,
        "family_members",
        ["family_id", "full_name", "name_norm", "name_key", "cin", "cin_norm", "phone", "phone_norm", "is_representative"],
        memberRows
      );
      await tx.query("INSERT INTO audit_logs (user_id, action, entity, details) VALUES (NULL, ?, ?, ?)", [
        "init_data",
        "import",
        JSON.stringify({ sponsors: sponsorRows.length, families: familyRows.length, members: memberRows.length, warnings: warnings.length }),
      ]);
    });

    return res.status(200).json({
      ok: true,
      inserted: { sponsors: sponsorRows.length, families: familyRows.length, members: memberRows.length },
      warnings,
    });
  } catch (error) {
    console.error("initData error:", error);
    return res.status(500).json({ ok: false, error: error.code || "Erreur serveur", message: error.sqlMessage || error.message });
  }
}